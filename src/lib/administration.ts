async function getOrCreateSettingRow<T extends "notification_settings" | "security_settings">(
  context: RequestContext,
  table: T
) {
  const existing = await context.admin
    .from(table)
    .select("*")
    .eq("company_id", context.profile.company_id)
    .maybeSingle();

  if (existing.data) {
    return existing.data;
  }

  const { data, error } = await context.admin
    .from(table)
    .upsert({ company_id: context.profile.company_id }, { onConflict: "company_id" })
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error(`${table}_create_failed`);
  }

  return data;
}

