function parseCsvContent(content: string) {
  const rows: string[][] = [];
  let current = "";
  let row: string[] = [];
  let insideQuotes = false;

  for (let index = 0; index < content.length; index += 1) {
    const character = content[index];
    const next = content[index + 1];

    if (character === "\"") {
      if (insideQuotes && next === "\"") {
        current += "\"";
        index += 1;
      } else {
        insideQuotes = !insideQuotes;
      }
      continue;
    }

    if (character === "," && !insideQuotes) {
      row.push(current.trim());
      current = "";
      continue;
    }

    if ((character === "\n" || character === "\r") && !insideQuotes) {
      if (character === "\r" && next === "\n") {
        index += 1;
      }
      row.push(current.trim());
      current = "";
      if (row.some((value) => value.length > 0)) {
        rows.push(row);
      }
      row = [];
      continue;
    }

    current += character;
  }

  row.push(current.trim());
  if (row.some((value) => value.length > 0)) {
    rows.push(row);
  }

  const [header = [], ...body] = rows;
  return {
    header,
    body: body.map((values) =>
      Object.fromEntries(header.map((column, columnIndex) => [column, values[columnIndex] ?? ""]))
    ),
  };
}

async function resolveCompanyLookups(context: RequestContext) {
  const [branches, departments] = await Promise.all([
    listCompanyScopedLookup("branches", context.profile.company_id),
    listCompanyScopedLookup("departments", context.profile.company_id),
  ]);

  return {
    branchByCode: new Map(branches.map((branch) => [safeString(branch.code), safeString(branch.id)])),
    departmentByCode: new Map(departments.map((department) => [safeString(department.code), safeString(department.id)])),
  };
}

export async function listDataImportJobs() {
  const context = await getRequestContext();
  ensureAdminAccess(context.profile);

  const { data, error } = await context.admin
    .from("data_import_jobs")
    .select("*")
    .eq("company_id", context.profile.company_id)
    .order("created_at", { ascending: false })
    .limit(50);

  if (error) {
    throw error;
  }

  return data ?? [];
}

export async function runDataImport(input: {
  importType: "employees" | "branches" | "departments" | "designations" | "job_grades" | "payroll_groups";
  fileName: string;
  content: string;
  previewOnly?: boolean;
}) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  const parsed = parseCsvContent(input.content);
  const errors: Array<{ row: number; message: string }> = [];
  let successCount = 0;

  const job = await context.admin
    .from("data_import_jobs")
    .insert({
      company_id: context.profile.company_id,
      import_type: input.importType,
      file_name: input.fileName,
      status: input.previewOnly ? "preview" : "processing",
      row_count: parsed.body.length,
      created_by: context.profile.id,
    })
    .select("*")
    .single();

  if (job.error || !job.data) {
    throw job.error ?? new Error("import_job_create_failed");
  }

  const lookupMaps = await resolveCompanyLookups(context);
  const admin = createSupabaseAdminClient();

  for (const [index, row] of parsed.body.entries()) {
    try {
      if (input.importType === "branches") {
        if (!safeString(row.code) || !safeString(row.name)) {
          throw new Error("Branch import requires code and name.");
        }
        if (!input.previewOnly) {
          await context.admin.from("branches").upsert({
            company_id: context.profile.company_id,
            code: safeString(row.code),
            name: safeString(row.name),
            location: safeString(row.location, null as never),
            contact_email: safeString(row.contact_email, null as never),
            contact_phone: safeString(row.contact_phone, null as never),
            status: safeString(row.status, "active"),
          }, { onConflict: "company_id,code" });
        }
      } else if (input.importType === "departments") {
        if (!safeString(row.code) || !safeString(row.name)) {
          throw new Error("Department import requires code and name.");
        }
        if (!input.previewOnly) {
          await context.admin.from("departments").upsert({
            company_id: context.profile.company_id,
            code: safeString(row.code),
            name: safeString(row.name),
            branch_id: lookupMaps.branchByCode.get(safeString(row.branch_code)) ?? null,
            status: safeString(row.status, "active"),
          }, { onConflict: "company_id,code" });
        }
      } else if (input.importType === "designations") {
        if (!safeString(row.code) || !safeString(row.title)) {
          throw new Error("Designation import requires code and title.");
        }
        if (!input.previewOnly) {
          await context.admin.from("designations").upsert({
            company_id: context.profile.company_id,
            code: safeString(row.code),
            title: safeString(row.title),
            status: safeString(row.status, "active"),
          }, { onConflict: "company_id,code" });
        }
      } else if (input.importType === "job_grades") {
        if (!safeString(row.code) || !safeString(row.name)) {
          throw new Error("Job grade import requires code and name.");
        }
        if (!input.previewOnly) {
          await context.admin.from("job_grades").upsert({
            company_id: context.profile.company_id,
            code: safeString(row.code),
            name: safeString(row.name),
            level_rank: safeNumber(row.level_rank, 1),
            status: safeString(row.status, "active"),
          }, { onConflict: "company_id,code" });
        }
      } else if (input.importType === "payroll_groups") {
        if (!safeString(row.name)) {
          throw new Error("Payroll group import requires name.");
        }
        if (!input.previewOnly) {
          await context.admin.from("payroll_groups").upsert({
            company_id: context.profile.company_id,
            name: safeString(row.name),
            frequency: safeString(row.frequency, "Monthly"),
            currency: safeString(row.currency, "KES"),
            cut_off_day: safeNumber(row.cut_off_day, 25),
            pay_day: safeNumber(row.pay_day, 28),
            status: safeString(row.status, "active"),
          }, { onConflict: "company_id,name" });
        }
      } else if (input.importType === "employees") {
        if (!safeString(row.employee_number) || !safeString(row.first_name) || !safeString(row.last_name)) {
          throw new Error("Employee import requires employee_number, first_name, and last_name.");
        }
        if (!input.previewOnly) {
          await admin.from("employees").upsert({
            company_id: context.profile.company_id,
            employee_number: safeString(row.employee_number),
            first_name: safeString(row.first_name),
            last_name: safeString(row.last_name),
            email: safeString(row.email, `${safeString(row.first_name)}.${safeString(row.last_name)}@solvahr.app`.toLowerCase()),
            phone: safeString(row.phone, "0700000000"),
            employment_type: safeString(row.employment_type, "Permanent"),
            department_id: lookupMaps.departmentByCode.get(safeString(row.department_code)) ?? null,
            branch_id: lookupMaps.branchByCode.get(safeString(row.branch_code)) ?? null,
            status: safeString(row.status, "Active"),
            salary: safeNumber(row.salary, 0),
          }, { onConflict: "employee_number" });
        }
      }

      successCount += 1;
    } catch (error) {
      errors.push({
        row: index + 2,
        message: error instanceof Error ? error.message : "Import row failed.",
      });
    }
  }

  const { data, error } = await context.admin
    .from("data_import_jobs")
    .update({
      status: input.previewOnly ? "preview" : errors.length > 0 ? "partial" : "completed",
      success_count: successCount,
      failure_count: errors.length,
      error_summary: errors,
    })
    .eq("id", safeString(job.data.id))
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error("import_job_update_failed");
  }

  await createAuditLog(context, {
    moduleKey: "administration",
    entityType: "data_import_job",
    entityId: safeString(data.id),
    action: input.previewOnly ? "previewed_data_import" : "executed_data_import",
    afterValue: data as Record<string, unknown>,
  });

  return data;
}

