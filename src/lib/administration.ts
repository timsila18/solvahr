async function getOrCreateCompanySettings(context: RequestContext) {
  const existing = await context.admin
    .from("company_settings")
    .select("*")
    .eq("company_id", context.profile.company_id)
    .maybeSingle();

  if (existing.data) {
    return existing.data;
  }

  const { data, error } = await context.admin
    .from("company_settings")
    .upsert({ company_id: context.profile.company_id }, { onConflict: "company_id" })
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error("company_settings_create_failed");
  }

  return data;
}

