async function getRequestContext(): Promise<RequestContext> {
  const supabase = await createSupabaseServerClient();
  const admin = createSupabaseAdminClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    throw new Error("unauthorized");
  }

  const { data } = await admin
    .from("users")
    .select("id, company_id, full_name, email, phone, role, employee_id, branch_id, department_id, last_login, status")
    .eq("id", user.id)
    .single();

  const profile: AuthUserProfile = data
    ? {
        ...data,
        role: normalizeRole(safeString(data.role)),
      }
    : {
        id: user.id,
        company_id: null,
        full_name: safeString(user.user_metadata.full_name, user.email ?? "Solva User"),
        email: user.email ?? "",
        phone: null,
        role: normalizeRole(safeString(user.app_metadata.role, "Employee")),
        employee_id: null,
        branch_id: null,
        department_id: null,
        last_login: null,
        status: "active",
      };

  if (["suspended", "deactivated", "revoked"].includes(profile.status.toLowerCase())) {
    throw new Error("forbidden");
  }

  return { supabase, admin, profile };
}

function ensureAdminAccess(profile: AuthUserProfile) {
  if (!ADMIN_ROLES.includes(profile.role as AdminRole)) {
    throw new Error("forbidden");
  }
}

function ensureAdminManageAccess(profile: AuthUserProfile) {
  if (!ADMIN_MANAGE_ROLES.includes(profile.role)) {
    throw new Error("forbidden");
  }
}

