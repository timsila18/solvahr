export async function cloneRoleDefinition(roleKey: string, cloneName: string) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  const [roleResult, permissionsResult] = await Promise.all([
    context.admin
      .from("role_definitions")
      .select("*")
      .eq("company_id", context.profile.company_id)
      .eq("role_key", roleKey)
      .single(),
    context.admin
      .from("role_permissions")
      .select("*")
      .eq("company_id", context.profile.company_id)
      .eq("role_key", roleKey),
  ]);

  if (roleResult.error || !roleResult.data) {
    throw roleResult.error ?? new Error("role_not_found");
  }

  const clonedKey = `${cloneName.toLowerCase().replace(/[^a-z0-9]+/g, "_")}_${Date.now().toString().slice(-4)}`;
  const created = await createRoleDefinition({
    roleKey: clonedKey,
    name: cloneName,
    description: `Template cloned from ${roleResult.data.name}.`,
    scopeType: safeString(roleResult.data.scope_type),
    assignable: false,
  });

  const clonedPermissions = (permissionsResult.data ?? []).map((permission) => ({
    company_id: context.profile.company_id,
    role_key: clonedKey,
    module_key: safeString(permission.module_key),
    scope_type: safeString(permission.scope_type),
    can_view: Boolean(permission.can_view),
    can_create: Boolean(permission.can_create),
    can_edit: Boolean(permission.can_edit),
    can_approve: Boolean(permission.can_approve),
    can_export: Boolean(permission.can_export),
    can_delete: Boolean(permission.can_delete),
    can_admin: Boolean(permission.can_admin),
    status: safeString(permission.status, "active"),
  }));

  if (clonedPermissions.length > 0) {
    await context.admin.from("role_permissions").insert(clonedPermissions);
  }

  return created;
}

