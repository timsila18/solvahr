export async function createAdminUser(input: {
  fullName: string;
  email: string;
  phone?: string | null;
  role: AppRole;
  employeeId?: string | null;
  branchId?: string | null;
  departmentId?: string | null;
  inviteOnly?: boolean;
  temporaryPassword?: string | null;
}) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);
  await assertAdminPlanCapacity(context.profile.company_id);

  if (input.inviteOnly) {
    const invite = await inviteUser({
      email: input.email,
      fullName: input.fullName,
      role: input.role,
      employeeId: input.employeeId,
      branchId: input.branchId,
      departmentId: input.departmentId,
    });

    const admin = createSupabaseAdminClient();
    await admin
      .from("users")
      .update({
        phone: input.phone ?? null,
        invited_by: context.profile.id,
        invited_at: new Date().toISOString(),
        activation_state: "invited",
        must_reset_password: true,
      })
      .eq("id", invite.id);

    return {
      ...invite,
      inviteOnly: true,
    };
  }

  const temporaryPassword = input.temporaryPassword?.trim() || generateTemporaryPassword();
  const admin = createSupabaseAdminClient();
  const created = await admin.auth.admin.createUser({
    email: input.email,
    password: temporaryPassword,
    email_confirm: true,
    user_metadata: {
      full_name: input.fullName,
      phone: input.phone ?? null,
    },
    app_metadata: {
      role: input.role,
    },
  });

  if (created.error || !created.data.user) {
    throw created.error ?? new Error("user_create_failed");
  }

  const { data, error } = await admin
    .from("users")
    .upsert({
      id: created.data.user.id,
      company_id: context.profile.company_id,
      full_name: input.fullName,
      email: input.email,
      phone: input.phone ?? null,
      role: input.role,
      employee_id: input.employeeId ?? null,
      branch_id: input.branchId ?? null,
      department_id: input.departmentId ?? null,
      status: "active",
      activation_state: "active",
      invited_by: context.profile.id,
      invited_at: new Date().toISOString(),
      activated_at: new Date().toISOString(),
      must_reset_password: true,
    })
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error("user_profile_upsert_failed");
  }

  await Promise.all([
    createAuditLog(context, {
      moduleKey: "administration",
      entityType: "user",
      entityId: safeString(data.id),
      action: "created_user_account",
      afterValue: data as Record<string, unknown>,
    }),
    recordAccessLogEntry({
      companyId: context.profile.company_id,
      userId: context.profile.id,
      userEmail: context.profile.email,
      userRole: context.profile.role,
      moduleKey: "administration",
      action: "create_user",
      recordType: "user",
      recordId: safeString(data.id),
      outcome: "success",
      details: { assignedRole: input.role },
    }),
  ]);

  return {
    id: safeString(data.id),
    email: input.email,
    role: input.role,
    temporaryPassword,
  };
}

function ensureAssignableRole(profile: AuthUserProfile, role: AppRole) {
  if (profile.role === "Super Admin") {
    return;
  }

  const allowedRoles: AppRole[] = ["Employee", "Manager", "Recruiter", "Supervisor", "Operator"];
  if (!allowedRoles.includes(role)) {
    throw new Error("forbidden");
  }
}

export async function createEmployeeLinkedUserAccounts(input: {
  employeeIds: string[];
  role?: AppRole;
}) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  const targetRole = normalizeRole(safeString(input.role, "Employee"));
  ensureAssignableRole(context.profile, targetRole);

  const employeeIds = Array.from(new Set(input.employeeIds.filter(Boolean)));
  if (!employeeIds.length) {
    throw new Error("employee_selection_required");
  }

  const employeeResult = await context.admin
    .from("employees")
    .select(
      "id, employee_number, first_name, last_name, email, phone, branch_id, department_id, linked_user:users!users_employee_id_fkey(id, email, role, status)"
    )
    .eq("company_id", context.profile.company_id)
    .in("id", employeeIds);

  if (employeeResult.error) {
    throw employeeResult.error;
  }

  const created: Array<{
    employeeId: string;
    email: string;
    role: string;
    userId: string | null;
    temporaryPassword?: string | null;
  }> = [];
  const skipped: Array<{ employeeId: string; employeeName: string; reason: string }> = [];
  const failed: Array<{ employeeId: string; employeeName: string; reason: string }> = [];

  for (const row of employeeResult.data ?? []) {
    const employee = row as Record<string, unknown>;
    const employeeId = safeString(employee.id);
    const employeeName = `${safeString(employee.first_name)} ${safeString(employee.last_name)}`.trim();
    const linkedUser = asRecord(employee.linked_user);
    const email = safeString(employee.email).trim().toLowerCase();

    if (linkedUser?.id) {
      skipped.push({ employeeId, employeeName, reason: "User account already exists." });
      continue;
    }

    if (!email || !email.includes("@")) {
      skipped.push({ employeeId, employeeName, reason: "Employee does not have a valid email address." });
      continue;
    }

    try {
      const result = await createAdminUser({
        fullName: employeeName,
        email,
        phone: safeString(employee.phone) || null,
        role: targetRole,
        employeeId,
        branchId: safeString(employee.branch_id) || null,
        departmentId: safeString(employee.department_id) || null,
        inviteOnly: false,
        temporaryPassword: "RobotCafe123",
      });

      created.push({
        employeeId,
        email,
        role: targetRole,
        userId: safeString(result.id) || null,
        temporaryPassword: safeString((result as Record<string, unknown>).temporaryPassword) || null,
      });
    } catch (error) {
      failed.push({
        employeeId,
        employeeName,
        reason: error instanceof Error ? error.message : "Could not create the user account.",
      });
    }
  }

  return {
    role: targetRole,
    created,
    skipped,
    failed,
    summary: {
      requested: employeeIds.length,
      created: created.length,
      skipped: skipped.length,
      failed: failed.length,
    },
  };
}

export async function updateAdminUser(
  userId: string,
  input: {
    fullName?: string;
    phone?: string | null;
    role?: AppRole;
    employeeId?: string | null;
    branchId?: string | null;
    departmentId?: string | null;
  }
) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  const admin = createSupabaseAdminClient();
  const before = await admin.from("users").select("*").eq("id", userId).single();
  if (before.error || !before.data) {
    throw before.error ?? new Error("user_not_found");
  }

  const { data, error } = await admin
    .from("users")
    .update({
      ...(typeof input.fullName !== "undefined" ? { full_name: input.fullName } : {}),
      ...(typeof input.phone !== "undefined" ? { phone: input.phone } : {}),
      ...(typeof input.role !== "undefined" ? { role: input.role } : {}),
      ...(typeof input.employeeId !== "undefined" ? { employee_id: input.employeeId } : {}),
      ...(typeof input.branchId !== "undefined" ? { branch_id: input.branchId } : {}),
      ...(typeof input.departmentId !== "undefined" ? { department_id: input.departmentId } : {}),
    })
    .eq("id", userId)
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error("user_update_failed");
  }

  await admin.auth.admin.updateUserById(userId, {
    ...(typeof input.fullName !== "undefined" ? { user_metadata: { ...(before.data.user_metadata ?? {}), full_name: input.fullName } } : {}),
    ...(typeof input.role !== "undefined" ? { app_metadata: { role: input.role } } : {}),
  });

  await Promise.all([
    createAuditLog(context, {
      moduleKey: "administration",
      entityType: "user",
      entityId: userId,
      action: "updated_user_account",
      beforeValue: before.data as Record<string, unknown>,
      afterValue: data as Record<string, unknown>,
    }),
    recordAccessLogEntry({
      companyId: context.profile.company_id,
      userId: context.profile.id,
      userEmail: context.profile.email,
      userRole: context.profile.role,
      moduleKey: "administration",
      action: "update_user",
      recordType: "user",
      recordId: userId,
      outcome: "success",
    }),
  ]);

  return data;
}

export async function runAdminUserAction(
  userId: string,
  action:
    | "activate"
    | "suspend"
    | "deactivate"
    | "reactivate"
    | "resend_invite"
    | "reset_password"
    | "set_temporary_password"
    | "revoke_invite"
    | "force_sign_out",
  options?: {
    temporaryPassword?: string | null;
  }
) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  const admin = createSupabaseAdminClient();
  const before = await admin.from("users").select("*").eq("id", userId).single();
  if (before.error || !before.data) {
    throw before.error ?? new Error("user_not_found");
  }

  const user = before.data;
  const timestamp = new Date().toISOString();

  if (action === "resend_invite" || action === "reset_password") {
    const response = await admin.auth.resetPasswordForEmail(safeString(user.email), {
      redirectTo: getAuthCallbackUrl("/reset-password"),
    });

    if (response.error) {
      throw response.error;
    }
  }

  if (action === "force_sign_out") {
    await admin
      .from("login_sessions")
      .update({ active: false, updated_at: timestamp })
      .eq("user_id", userId)
      .eq("active", true);
  }

  let patch: Record<string, unknown> = {};
  let updated = user;
  if (action === "activate" || action === "reactivate") {
    const authUpdate = await admin.auth.admin.updateUserById(userId, {
      email_confirm: true,
    });

    if (authUpdate.error) {
      throw authUpdate.error;
    }

    patch = {
      status: "active",
      activation_state: "active",
      activated_at: timestamp,
      suspended_at: null,
      deactivated_at: null,
    };
  } else if (action === "suspend") {
    patch = {
      status: "suspended",
      activation_state: "suspended",
      suspended_at: timestamp,
    };
  } else if (action === "deactivate") {
    patch = {
      status: "deactivated",
      activation_state: "deactivated",
      deactivated_at: timestamp,
    };
  } else if (action === "revoke_invite") {
    patch = {
      status: "revoked",
      activation_state: "revoked",
      deactivated_at: timestamp,
    };
  } else if (action === "resend_invite") {
    patch = {
      status: "invited",
      activation_state: "invited",
      invited_at: timestamp,
      must_reset_password: true,
    };
  } else if (action === "reset_password") {
    patch = {
      must_reset_password: true,
    };
  } else if (action === "set_temporary_password") {
    const temporaryPassword = options?.temporaryPassword?.trim() || generateTemporaryPassword();
    const passwordUpdate = await admin.auth.admin.updateUserById(userId, {
      password: temporaryPassword,
      email_confirm: true,
    });

    if (passwordUpdate.error) {
      throw passwordUpdate.error;
    }

    patch = {
      must_reset_password: true,
    };

    const response = await admin.from("users").update(patch).eq("id", userId).select("*").single();
    if (response.error || !response.data) {
      throw response.error ?? new Error("user_action_failed");
    }
    updated = response.data;

    await Promise.all([
      createAuditLog(context, {
        moduleKey: "administration",
        entityType: "user",
        entityId: userId,
        action: "set_temporary_password",
        beforeValue: before.data as Record<string, unknown>,
        afterValue: {
          ...(updated as Record<string, unknown>),
          temporaryPasswordIssuedAt: timestamp,
        },
      }),
      recordAccessLogEntry({
        companyId: context.profile.company_id,
        userId: context.profile.id,
        userEmail: context.profile.email,
        userRole: context.profile.role,
        moduleKey: "administration",
        action: "set_temporary_password",
        recordType: "user",
        recordId: userId,
        outcome: "success",
      }),
    ]);

    return {
      id: safeString(updated.id),
      status: safeString(updated.status),
      activationState: safeString(updated.activation_state),
      action,
      temporaryPassword,
    };
  }

  if (Object.keys(patch).length > 0) {
    const response = await admin.from("users").update(patch).eq("id", userId).select("*").single();
    if (response.error || !response.data) {
      throw response.error ?? new Error("user_action_failed");
    }
    updated = response.data;
  }

  await Promise.all([
    createAuditLog(context, {
      moduleKey: "administration",
      entityType: "user",
      entityId: userId,
      action: `${action}_user_account`,
      beforeValue: before.data as Record<string, unknown>,
      afterValue: updated as Record<string, unknown>,
    }),
    recordAccessLogEntry({
      companyId: context.profile.company_id,
      userId: context.profile.id,
      userEmail: context.profile.email,
      userRole: context.profile.role,
      moduleKey: "administration",
      action,
      recordType: "user",
      recordId: userId,
      outcome: "success",
    }),
  ]);

  return {
    id: safeString(updated.id),
    status: safeString(updated.status),
    activationState: safeString(updated.activation_state),
    action,
  };
}

export async function listRoleDefinitions() {
  const context = await getRequestContext();
  ensureAdminAccess(context.profile);

  const [rolesResult, usersResult, permissionsResult] = await Promise.all([
    context.admin
      .from("role_definitions")
      .select("*")
      .eq("company_id", context.profile.company_id)
      .order("name", { ascending: true }),
    context.admin
      .from("users")
      .select("role")
      .eq("company_id", context.profile.company_id),
    context.admin
      .from("role_permissions")
      .select("role_key, module_key, can_view")
      .eq("company_id", context.profile.company_id),
  ]);

  if (rolesResult.error || usersResult.error || permissionsResult.error) {
    throw rolesResult.error ?? usersResult.error ?? permissionsResult.error ?? new Error("role_query_failed");
  }

  return (rolesResult.data ?? []).map((role) => ({
    id: safeString(role.id),
    roleKey: safeString(role.role_key),
    name: safeString(role.name),
    description: safeString(role.description),
    scopeType: safeString(role.scope_type),
    status: safeString(role.status),
    isSystem: Boolean(role.is_system),
    assignable: Boolean(role.assignable),
    userCount: (usersResult.data ?? []).filter((user) => safeString(user.role) === safeString(role.role_key)).length,
    modules: (permissionsResult.data ?? [])
      .filter((permission) => safeString(permission.role_key) === safeString(role.role_key) && Boolean(permission.can_view))
      .map((permission) => safeString(permission.module_key)),
  }));
}

