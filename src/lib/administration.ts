function safeString(value: unknown, fallback = "") {
  return typeof value === "string" ? value : fallback;
}

function safeNumber(value: unknown, fallback = 0) {
  if (typeof value === "number") {
    return value;
  }

  if (typeof value === "string" && value.length > 0) {
    const parsed = Number(value);
    return Number.isNaN(parsed) ? fallback : parsed;
  }

  return fallback;
}

function asRecord(value: unknown): Record<string, unknown> | null {
  if (Array.isArray(value)) {
    const [first] = value;
    return first && typeof first === "object" ? (first as Record<string, unknown>) : null;
  }

  if (value && typeof value === "object") {
    return value as Record<string, unknown>;
  }

  return null;
}

function toTitle(value: string) {
  return value
    .split(/[_\s-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function slugify(value: string) {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildLogoMark(displayName: string, identifier?: string | null) {
  const seed = safeString(identifier) || displayName;
  const words = seed
    .split(/[\s-]+/)
    .map((part) => part.trim())
    .filter(Boolean);
  const mark = (words.slice(0, 2).map((part) => part.charAt(0)).join("") || seed.slice(0, 2) || "S")
    .toUpperCase();
  return mark.slice(0, 2);
}

const DEFAULT_SOLVA_REPORT_FOOTER = "Generated by Solva HR - www.solvahr.co.ke";
const DEFAULT_POWERED_BY_LABEL = "Powered by Solva HR";

function normaliseBranding(
  rawBranding: Record<string, unknown> | null,
  company: Record<string, unknown> | null
) {
  const companyName = safeString(company?.name, "Solva HR Workspace");
  const employerIdentifier =
    safeString(rawBranding?.employerIdentifier) || safeString(company?.slug).toUpperCase() || "SOLVA";
  const displayName = safeString(rawBranding?.displayName, companyName);

  return {
    displayName,
    employerIdentifier,
    logoPath: safeString(rawBranding?.logoPath),
    logoUrl: safeString(rawBranding?.logoUrl),
    logoMark: safeString(rawBranding?.logoMark, buildLogoMark(displayName, employerIdentifier)),
    reportFooter: safeString(rawBranding?.reportFooter, DEFAULT_SOLVA_REPORT_FOOTER),
    accentColor: safeString(rawBranding?.accentColor, "#1d4ed8"),
    secondaryColor: safeString(rawBranding?.secondaryColor, "#0f172a"),
    companyShortName: safeString(rawBranding?.companyShortName, displayName),
    welcomeMessage: safeString(
      rawBranding?.welcomeMessage,
      `${displayName} HR platform, ${safeString(rawBranding?.poweredByLabel, DEFAULT_POWERED_BY_LABEL).toLowerCase()}.`
    ),
    emailSignature: safeString(
      rawBranding?.emailSignature,
      `${displayName}\n${DEFAULT_POWERED_BY_LABEL}\nwww.solvahr.co.ke`
    ),
    poweredByLabel: safeString(rawBranding?.poweredByLabel, DEFAULT_POWERED_BY_LABEL),
  };
}

async function createBrandingLogoUrl(branding: {
  logoPath?: string;
  logoUrl?: string;
}) {
  if (branding.logoUrl) {
    return branding.logoUrl;
  }

  if (!branding.logoPath) {
    return "";
  }

  const admin = createSupabaseAdminClient();
  const bucket = getStorageBucketNames().payrollDocuments;
  const signed = await admin.storage.from(bucket).createSignedUrl(branding.logoPath, 60 * 60 * 24 * 7);
  if (signed.error || !signed.data?.signedUrl) {
    return "";
  }
  return signed.data.signedUrl;
}

