export async function uploadCompanyLogo(input: { file: File }) {
  const context = await getRequestContext();
  ensureAdminManageAccess(context.profile);

  if (!context.profile.company_id) {
    throw new Error("missing_company_context");
  }

  const file = input.file;
  if (!file || !file.size) {
    throw new Error("logo_file_missing");
  }

  if (!/^image\/(png|jpeg|jpg|webp|svg\+xml)$/i.test(file.type)) {
    throw new Error("logo_file_type_not_supported");
  }

  const ext = file.name.split(".").pop() ?? "png";
  const bucket = getStorageBucketNames().payrollDocuments;
  const path = `companies/${context.profile.company_id}/branding/logo-${Date.now()}.${ext}`;
  const buffer = Buffer.from(await file.arrayBuffer());

  const uploadResult = await context.admin.storage.from(bucket).upload(path, buffer, {
    contentType: file.type,
    upsert: true,
  });

  if (uploadResult.error) {
    throw uploadResult.error;
  }

  const companyResult = await context.admin
    .from("companies")
    .select("name, slug")
    .eq("id", context.profile.company_id)
    .single();

  if (companyResult.error || !companyResult.data) {
    throw companyResult.error ?? new Error("company_not_found");
  }

  const existingSettings = await getOrCreateCompanySettings(context);
  const existingBranding = normaliseBranding(
    asRecord((existingSettings as Record<string, unknown> | null)?.branding),
    companyResult.data as Record<string, unknown>
  );
  const signedUrl = await createBrandingLogoUrl({ logoPath: path });
  const branding = {
    ...existingBranding,
    logoPath: path,
    logoUrl: signedUrl,
    logoMark: buildLogoMark(existingBranding.displayName, existingBranding.employerIdentifier),
  };

  const { data, error } = await context.admin
    .from("company_settings")
    .upsert(
      {
        company_id: context.profile.company_id,
        branding,
      },
      { onConflict: "company_id" }
    )
    .select("*")
    .single();

  if (error || !data) {
    throw error ?? new Error("company_logo_update_failed");
  }

  await createAuditLog(context, {
    moduleKey: "administration",
    entityType: "company_branding",
    entityId: context.profile.company_id,
    action: "uploaded_company_logo",
    afterValue: {
      logoPath: path,
      logoUrl: signedUrl,
    },
  });

  return {
    branding: {
      ...branding,
      logoUrl: signedUrl,
    },
  };
}

